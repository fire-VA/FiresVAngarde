using System;
using HarmonyLib;
using UnityEngine;

namespace VerdantsAscent.Modules.AntiCheat
{
    /// <summary>
    /// Harmony patches for VAngarde anti-cheat system.
    ///
    /// Hooks into the ZNet lifecycle to:
    ///  1. Initialize VAngarde on server start (ZNet.Awake)
    ///  2. Register per-peer RPCs when a new connection arrives (ZNet.OnNewConnection)
    ///  3. Send challenge after peer validation (ZNet.RPC_PeerInfo postfix)
    ///  4. Run periodic checks (ZNet.Update)
    ///  5. Clean up on disconnect (ZNet.Disconnect)
    ///  6. Shutdown on ZNet destroy (ZNet.OnDestroy)
    ///
    /// These patches are SERVER-ONLY where noted. Client patches only register
    /// the response handler so the client can answer server challenges.
    /// </summary>
    [HarmonyPatch]
    public static class VAngardePatches
    {
        // ??????????????????????????????????????????????????????????????
        // ZNet.Awake — Initialize VAngarde on server
        // ??????????????????????????????????????????????????????????????

        [HarmonyPatch(typeof(ZNet), "Awake")]
        [HarmonyPostfix]
        [HarmonyPriority(Priority.Low)] // run after other mods register their RPCs
        public static void ZNet_Awake_Postfix(ZNet __instance)
        {
            try
            {
                if (__instance.IsServer())
                {
                    VAngardeCore.Initialize();
                }
            }
            catch (Exception ex)
            {
                Debug.LogWarning($"[VAngarde] Awake init error: {ex.Message}");
            }
        }

        // ??????????????????????????????????????????????????????????????
        // ZNet.OnNewConnection — Register per-peer RPCs
        // ??????????????????????????????????????????????????????????????

        [HarmonyPatch(typeof(ZNet), "OnNewConnection")]
        [HarmonyPostfix]
        public static void ZNet_OnNewConnection_Postfix(ZNet __instance, ZNetPeer peer)
        {
            if (peer?.m_rpc == null) return;

            try
            {
                if (!__instance.IsServer())
                {
                    // Client: register the challenge handler on this peer's ZRpc.
                    // The challenge payload is tiny (nonce + timestamp) so per-peer ZRpc
                    // is fine here. The RESPONSE goes back via ZRoutedRpc instead
                    // (registered in the Awake hook below) because it can carry a
                    // multi-MB chunked log and ZRpc's underlying socket layer
                    // concatenates queued packages into one Steam message that blows
                    // past the 512KB SendMessageToConnection cap. ZRoutedRpc avoids
                    // that pathology — same pattern as RuntimeSpriteSync (50MB sprites).
                    peer.m_rpc.Register<ZPackage>(VAngardeCore.RPC_Challenge,
                        new Action<ZRpc, ZPackage>(VAngardeCore.HandleServerChallenge));

                    // Hardening v2 — receive the server's session UID (encrypted with the baked
                    // AES key) on a separate small RPC. Stored client-side and used to sign each
                    // challenge response so wire forgers and cross-session replays don't pass.
                    peer.m_rpc.Register<ZPackage>(VAngardeSession.RpcSessionInit,
                        new Action<ZRpc, ZPackage>(VAngardeSession.OnClientReceiveUid));
                }
            }
            catch (Exception ex)
            {
                Debug.LogWarning($"[VAngarde] OnNewConnection RPC registration error: {ex.Message}");
            }
        }

        // ??????????????????????????????????????????????????????????????
        // ZNet.Awake — Register routed RPCs (admin push)
        // ??????????????????????????????????????????????????????????????

        [HarmonyPatch(typeof(ZNet), "Awake")]
        [HarmonyPostfix]
        [HarmonyPriority(Priority.LowerThanNormal)]
        public static void ZNet_Awake_RegisterRoutedRPCs(ZNet __instance)
        {
            try
            {
                // Register routed RPC for admin mod list push (works on both server and client)
                ZRoutedRpc.instance?.Register<ZPackage>(VAngardeCore.RPC_Push,
                    new Action<long, ZPackage>(VAngardeCore.RPC_OnAdminPushModList));

                // Register the challenge-response RPC on the routed transport.
                // Client invokes ZRoutedRpc.InvokeRoutedRPC(serverPeerId, RPC_Response, pkg)
                // for both single-shot and chunked log payloads. Server-side handler
                // looks up the PeerState by the routed-RPC sender id.
                ZRoutedRpc.instance?.Register<ZPackage>(VAngardeCore.RPC_Response,
                    new Action<long, ZPackage>(VAngardeCore.RPC_OnChallengeResponse));

                // Admin cheat-command snapshot (client -> server). Server resolves the admin status
                // from the routed sender id, so a non-admin spoofing this is ignored.
                ZRoutedRpc.instance?.Register<ZPackage>(VAngardeCore.RPC_AdminSnapshot,
                    new Action<long, ZPackage>(VAngardeCore.RPC_OnAdminSnapshot));
            }
            catch (Exception ex)
            {
                Debug.LogWarning($"[VAngarde] Failed to register routed RPCs: {ex.Message}");
            }
        }

        // ??????????????????????????????????????????????????????????????
        // ZNet.RPC_PeerInfo — Send challenge after successful validation
        // ??????????????????????????????????????????????????????????????

        [HarmonyPatch(typeof(ZNet), "RPC_PeerInfo")]
        [HarmonyPostfix]
        public static void ZNet_RPC_PeerInfo_Postfix(ZNet __instance, ZRpc rpc)
        {
            if (!__instance.IsServer()) return;

            try
            {
                // Find the peer that was just validated
                var peers = __instance.GetPeers();
                if (peers == null) return;

                foreach (var peer in peers)
                {
                    if (peer.m_rpc == rpc)
                    {
                        VAngardeCore.OnPeerValidated(peer);
                        break;
                    }
                }
            }
            catch (Exception ex)
            {
                Debug.LogWarning($"[VAngarde] RPC_PeerInfo postfix error: {ex.Message}");
            }
        }

        // ??????????????????????????????????????????????????????????????
        // ZNet.Update — Periodic checks (server only)
        // ??????????????????????????????????????????????????????????????

        [HarmonyPatch(typeof(ZNet), "Update")]
        [HarmonyPostfix]
        public static void ZNet_Update_Postfix(ZNet __instance)
        {
            if (!__instance.IsServer()) return;

            try
            {
                VAngardeCore.ServerUpdate();
            }
            catch (Exception ex)
            {
                // Don't spam — only log once per minute
                Debug.LogWarning($"[VAngarde] Update error: {ex.Message}");
            }
        }

        // ??????????????????????????????????????????????????????????????
        // ZNet.Disconnect — Clean up tracking
        // ??????????????????????????????????????????????????????????????

        [HarmonyPatch(typeof(ZNet), "Disconnect")]
        [HarmonyPostfix]
        public static void ZNet_Disconnect_Postfix(ZNetPeer peer)
        {
            try
            {
                VAngardeCore.OnPeerDisconnected(peer);
            }
            catch { }
        }

        // ??????????????????????????????????????????????????????????????
        // ZNet.OnDestroy — Shutdown VAngarde
        // ??????????????????????????????????????????????????????????????

        [HarmonyPatch(typeof(ZNet), "OnDestroy")]
        [HarmonyPostfix]
        public static void ZNet_OnDestroy_Postfix()
        {
            try
            {
                VAngardeCore.Shutdown();
            }
            catch { }
        }
    }
}
